function S = scenario_defs()
%SCENARIO_DEFS 预置仿真场景定义 (目标初始状态 + 机动段 + 变速段)
%
%   返回结构体数组, 每个元素:
%     .name    场景标识: 'maneuver' | 'parallel' | 'crossing' | 'speed'
%     .label   中文名称 (用于图题与打印)
%     .targets 1×2 cell, 每个为目标初始状态 [x; y; vx; vy]
%     .turns   1×2 cell, 每个为 N×3 [起始步, 结束步, 转弯率(deg/s)]
%     .accel   1×2 cell, 每个为 N×3 [起始步, 结束步, 切向加速度(m/s^2)]
%
%   转弯率 > 0 为逆时针 (左转), < 0 为顺时针 (右转);
%   切向加速度沿当前航向, > 0 加速, < 0 减速.
%
%   新增场景时在此追加一个元素即可 (init_parameters 通过 apply_scenario 读取).

S = struct('name', {}, 'label', {}, 'targets', {}, 'turns', {}, 'accel', {});

% ---------------- 1. 双目标协调转弯 (默认场景) ----------------
S(1).name = 'maneuver';
S(1).label = '双目标协调转弯';
S(1).targets = {[200; 300; 1; 5], [800; 300; 0; 8]};
S(1).turns = {[35, 60, 6], [55, 80, -6]};
S(1).accel = {zeros(0, 3), zeros(0, 3)};

% ---------------- 2. 匀速平行运动 ----------------
% 两目标同向同速 (3,4) m/s, 横向间距 400 m, 间距保持不变
S(2).name = 'parallel';
S(2).label = '匀速平行运动';
S(2).targets = {[250; 400; 3; 4], [650; 400; 3; 4]};
S(2).turns = {zeros(0, 3), zeros(0, 3)};
S(2).accel = {zeros(0, 3), zeros(0, 3)};

% ---------------- 3. 匀速交叉运动 ----------------
% 两目标等速对穿, 航迹交叉点附近最近距离 100 m (第 50 步)
S(3).name = 'crossing';
S(3).label = '匀速交叉运动';
S(3).targets = {[150; 350; 6; 5], [750; 250; -6; 5]};
S(3).turns = {zeros(0, 3), zeros(0, 3)};
S(3).accel = {zeros(0, 3), zeros(0, 3)};

% ---------------- 4. 一匀速 + 一变加速 ----------------
% 目标1 匀速 5 m/s; 目标2 以 6 m/s 出发, 先加速 (0.06 m/s^2) 再减速 (-0.06 m/s^2)
S(4).name = 'speed';
S(4).label = '一匀速 + 一变速';
S(4).targets = {[200; 300; 0; 5], [800; 300; 0; 6]};
S(4).turns = {zeros(0, 3), zeros(0, 3)};
S(4).accel = {zeros(0, 3), [25, 55, 0.06; 65, 95, -0.06]};
end
